/**
 * The display face: a pixel Fraktur, for the handful of things the game says
 * in a raised voice.
 *
 * ## What it is for
 *
 * The title, a floor's name, a boss room's plate, the word a run ends on.
 * Nothing else. It is not a second UI font and it must never be used for a
 * label, a price or a prompt — see `docs/DECISIONS.md` #44, which is also
 * where the "never below its authored size" rule lives.
 *
 * ## The cell
 *
 * ```text
 * rows 0-1    diacritic band
 * row  2      clearance
 * rows 3-13   capitals and ascenders  (cap height 11)
 * rows 7-13   x-height                (x-height 7)
 * rows 14-15  descenders
 * ```
 *
 * Two and a half times the text face's cap height, and that is the point: a
 * broken script is *made of* its breaks, and a break needs at least three
 * pixels to read as a deliberate angle rather than as a rendering artefact.
 * Fraktur at the text face's 7-row caps is a smudge; at 11 it is a script.
 *
 * ## What is authentic, and what was given up
 *
 * Kept, because they are what makes the script Fraktur rather than a heavy
 * sans:
 *
 * - **Broken strokes.** Curves are built from straight facets meeting at
 *   angles. There is no circle in this face; `o` is a faceted lozenge.
 * - **Two-pixel stems with diamond spurs** — a spur left at the top of a
 *   stem, right at the foot. That, repeated, is the "picket fence" rhythm a
 *   line of blackletter reads as before any individual letter does.
 * - **The Elefantenrüssel**, the hooked flourish off a capital's shoulder, on
 *   the capitals with room for one.
 * - **Narrow, tightly spaced letters**, so a word reads as one dark mass.
 *
 * Given up, deliberately, and each for the same reason — a player has about
 * half a second to read a boss plate:
 *
 * - **The long ſ.** Authentic Fraktur switches between long and round s by
 *   position. That is a *typesetting* rule, not a glyph, it would need text
 *   analysis at draw time, and to a modern reader `ſ` reads as `f`.
 * - **The most ornate capitals.** Real Fraktur `A`/`U`, `B`/`V`, `C`/`E`,
 *   `I`/`J`, `K`/`R`, `M`/`W` are famously confusable pairs even to people who
 *   grew up reading them. Where authenticity and telling two letters apart
 *   disagreed, telling them apart won, so these capitals keep their modern
 *   skeletons and wear Fraktur's weight and breaks on top.
 * - **Ligatures** (ch, ck, tz, and ß's own descent from ſz). `ß` is here as a
 *   letter, because German needs it; the rest are typesetting again.
 *
 * ## Coverage
 *
 * A–Z, a–z, 0–9, ß, the punctuation a heading uses, and every accented
 * Latin-1 letter by composition over those bases. **Everything else falls
 * back to the text face**, baseline-aligned (`font-compile.ts`'s `PixelFace`
 * fallback). A display face legitimately needs fewer characters than a text
 * face — nothing writes a paragraph in it — but a heading that hits a
 * character nobody drew must show a letter rather than a box.
 */

